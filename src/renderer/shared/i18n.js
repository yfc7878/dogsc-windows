const DICTIONARIES = { "zh-Hans": ZH_HANS, en: EN };

let currentLocale = "zh-Hans";

export function setLocale(locale) {
  currentLocale = DICTIONARIES[locale] ? locale : "zh-Hans";
  document.documentElement.setAttribute("lang", currentLocale === "en" ? "en" : "zh-CN");
}

export function getLocale() {
  return currentLocale;
}

/**
 * Localises a Chinese source string. Supports the same positional `%@` / `%d`
 * / `%lld` placeholders the macOS original uses, plus `%%` for a literal %.
 */
export function t(key, ...args) {
  const table = DICTIONARIES[currentLocale] || ZH_HANS;
  let value = Object.prototype.hasOwnProperty.call(table, key) ? table[key] : key;
  if (!args.length) return value.replace(/%%/g, "%");
  let index = 0;
  value = value.replace(/%(?:lld|ld|d|@|\.2f|\.1f|f)/g, (match) => {
    const next = args[index++];
    if (next === undefined) return match;
    if (match === "%.2f") return Number(next).toFixed(2);
    if (match === "%.1f") return Number(next).toFixed(1);
    return String(next);
  });
  return value.replace(/%%/g, "%");
}

/** Convenience wrapper matching the original's `appLocalized`. */
export const L = t;

export function applyStaticTranslations(root = document) {
  for (const node of root.querySelectorAll("[data-i18n]")) {
    node.textContent = t(node.getAttribute("data-i18n"));
  }
  for (const node of root.querySelectorAll("[data-i18n-title]")) {
    node.setAttribute("title", t(node.getAttribute("data-i18n-title")));
  }
  for (const node of root.querySelectorAll("[data-i18n-placeholder]")) {
    node.setAttribute("placeholder", t(node.getAttribute("data-i18n-placeholder")));
  }
  for (const node of root.querySelectorAll("[data-i18n-aria]")) {
    node.setAttribute("aria-label", t(node.getAttribute("data-i18n-aria")));
  }
}
